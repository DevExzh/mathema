fn check(rows: &[(&str, &str)]) {
    let failures: Vec<String> = rows
        .iter()
        .filter_map(|&(input, wanted)| {
            let found = convert(input, Format::UnicodeMath, Format::LaTeX).unwrap();
            (found != wanted).then(|| format!("{input}: found {found}, wanted {wanted}"))
        })
        .collect();
    assert!(
        failures.is_empty(),
        "{} of {} rows failed:\n{}",
        failures.len(),
        rows.len(),
        failures.join("\n")
    );
}

#[test]
fn bars_pair_as_section_3_1_says() {
    check(BARS);
}

#[test]
fn bar_scan_is_linear() {
    // Each would take minutes if a bar or bracket rescanned the others.
    for unit in [
        "|", "‖", "|x/y|", "⟨|", "|⟩", "⟨&", "‖⟩", "(|", "|x ", "⟨x| ", "a|b,", "‖|", "x|_0",
    ] {
        let input = unit.repeat(40_000 / unit.len());
        convert(&input, Format::UnicodeMath, Format::MathML).ok();
    }
}
