#!/usr/bin/env python3
"""Generate src/unicode/math_class.rs.

usage: gen_math_class.py MathClassEx-15.txt > src/unicode/math_class.rs

The input is Unicode's MathClassEx, revision 15:
  https://www.unicode.org/Public/math/latest/MathClassEx-15.txt
  sha256 5a9719c813a5344e272ae587fce6fcbe91213583d60e2ea8a1b4e74d572c820c
  (c) 2017 Unicode(R), Inc.; see LICENSE-UNICODE.

The output depends on that file only: which characters are symbols is decided
by their class (`A`, letters, and `D`, `G`, `S`, `X` are left out) and by SKIP.
"""
import hashlib
import sys

SHA256 = "5a9719c813a5344e272ae587fce6fcbe91213583d60e2ea8a1b4e74d572c820c"
KIND = {
    "R": "Relation",
    "B": "BinaryOp",
    "V": "BinaryOp",
    "O": "Open",
    "C": "Close",
    "P": "Punctuation",
    "L": "LargeOp",
    "F": "Fence",
    "N": "Ordinary",
    "U": "Ordinary",
}
# Not symbols of their own in UnicodeMath: the radicals (constructs), and the
# superscript and subscript signs and parentheses (scripts, UTN #28 section
# 3.12); the letters, digits and fractions of class N and others; and the
# invisible operators.
SKIP = {
    0xB2, 0xB3, 0xB5, 0xB9, 0xBC, 0xBD, 0xBE, 0x03D8, 0x03D9,
    0x2107, 0x210E, 0x210F, 0x2126, 0x2132, 0x213E, *range(0x2145, 0x214A),
    *range(0x2061, 0x2065),
    0x0606, 0x0607, 0x306E, *range(0x1D7CE, 0x1D800),
    *range(0x221A, 0x221D),
    *range(0x207A, 0x207F),
    *range(0x208A, 0x208F),
}

data = open(sys.argv[1], "rb").read()
if hashlib.sha256(data).hexdigest() != SHA256:
    sys.exit("not the expected MathClassEx-15.txt")

ranges = []
for line in data.decode("utf-8").splitlines():
    if line.startswith("#") or ";" not in line:
        continue
    fields = line.split(";")
    ends = [int(end, 16) for end in fields[0].strip().split("..")]
    kind, name = KIND.get(fields[1].strip()), fields[-1].strip()
    if kind is None:
        continue
    for code in range(ends[0], ends[-1] + 1):
        if code < 0x80 or code in SKIP:
            continue
        if ranges and ranges[-1][1] == code - 1 and ranges[-1][2] == kind:
            ranges[-1][1] = code
        else:
            ranges.append([code, code, kind])
ranges.sort()

print('''//! Math classes of the Unicode math symbols, for glyphs no LaTeX command spells.
//!
//! Generated by `scripts/gen_math_class.py` from Unicode's `MathClassEx`,
//! revision 15
//! (<https://www.unicode.org/Public/math/latest/MathClassEx-15.txt>, sha256
//! `5a9719c813a5344e272ae587fce6fcbe91213583d60e2ea8a1b4e74d572c820c`).
//! © 2017 Unicode®, Inc. Used under the Unicode License V3; see
//! `LICENSE-UNICODE`. Do not edit by hand.

use crate::ast::SymbolKind;
use crate::ast::SymbolKind::{
    BinaryOp, Close, Fence, LargeOp, Open, Ordinary, Punctuation, Relation,
};

/// Sorted, disjoint, inclusive ranges.
#[rustfmt::skip]
static RANGES: &[(char, char, SymbolKind)] = &[''')
for first, last, kind in ranges:
    print(f"    ('\\u{{{first:X}}}', '\\u{{{last:X}}}', {kind}),")
print('''];

/// The math class of `ch`, if it is a math symbol.
pub(crate) fn math_class(ch: char) -> Option<SymbolKind> {
    let index = RANGES.partition_point(|&(_, last, _)| last < ch);
    let &(first, _, kind) = RANGES.get(index)?;
    (first <= ch).then_some(kind)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ranges_are_sorted_and_disjoint() {
        assert!(RANGES.iter().all(|(first, last, _)| first <= last));
        assert!(RANGES.windows(2).all(|pair| pair[0].1 < pair[1].0));
    }
}''')
