#!/usr/bin/env python3
"""Write fuzz/dict/latex.dict, a libFuzzer dictionary of what the LaTeX reader
knows, from the string literals of the reader's own sources.

Run it from the repository root after adding commands or environments:

    python3 scripts/gen_latex_dict.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src"


def source(path):
    """A Rust source without its test module and comments."""
    text = path.read_text(encoding="utf-8").split("\n#[cfg(test)]\nmod ")[0]
    return re.sub(r"(?m)^\s*//.*$", "", text)


def literals(text):
    for m in re.finditer(r'"((?:[^"\\]|\\.)*)"', text):
        yield m.group(1)


tokens = set()
control_word = re.compile(r"[A-Za-z@]+\*?")

# Names in match arms and tables: commands without their backslash.
files = [p for p in (SRC / "latex").rglob("*.rs") if p.name != "tests.rs"]
files.append(SRC / "unicode" / "symbols.rs")
for path in sorted(files):
    for text in literals(source(path)):
        if control_word.fullmatch(text) and len(text) < 40:
            tokens.add("\\" + text)
        elif re.fullmatch(r"\\\\[A-Za-z]+", text):
            tokens.add(text[1:])

# Environments.
environments = set()
for path in sorted(files):
    body = source(path)
    for m in re.finditer(r"fn parse_environment.*?\n    }\n", body, re.S):
        environments |= {t for t in literals(m.group(0)) if control_word.fullmatch(t)}
environments |= {
    b + s + star
    for b in "bBpvV"
    for s in ["matrix", "smallmatrix"]
    for star in ["", "*"]
}
for name in environments:
    tokens |= {f"\\begin{{{name}}}", f"\\end{{{name}}}"}

# Punctuation of the grammar and of the mini languages (CD, xymatrix, mhchem,
# siunitx, colors, column preambles, lengths, character codes).
tokens |= set(
    r"""\\ \( \) \[ \] \{ \} \| \, \: \; \! \> \  \' \" \^ \` \~ \= \. \# \$ \% \& \_
    @> @< @V @A @. @= @| @\vert ->[ <=> <-> \ar[r] \ar@{->} @/^/ |{ [rd] ^{ _{ }{ ]{ [t] &= '' _^ ^_
    |c| @{x} !{x} p{1cm} *{2}{c} >{ <{ red!50!blue [HTML]{ [rgb]{ #abcdef 1em 2mu -3pt 1.5cm
    \char"41 \char`\^ \char'7 \verb|x| %% ## #1 ~ \left( \right) \left. \right. \middle|
    SO4^2- ^{14}_6 (aq) #3 \bond{ 1.2e3 (5) \per\metre""".split()
) | {"\\ ", "%\n", "\\\n"}

# Letters and marks of each encoded length, spaces, and a combining mark.
tokens |= set("éßα中𝐀∑∫→′²₃⏞⎴‾") | {"́", "̸", "⃗", "　", " ", " ", "​", "\0"}


def quoted(token):
    out = []
    for byte in token.encode():
        if byte in b'"\\':
            out.append("\\" + chr(byte))
        elif 0x20 <= byte < 0x7F:
            out.append(chr(byte))
        else:
            out.append(f"\\x{byte:02X}")
    return '"' + "".join(out) + '"'


lines = [
    "# libFuzzer dictionary of the LaTeX reader.",
    "# Generated by scripts/gen_latex_dict.py; do not edit.",
]
# libFuzzer keeps at most 64 bytes of a word.
lines += sorted(quoted(t) for t in tokens if len(t.encode()) <= 64)
out = ROOT / "fuzz" / "dict" / "latex.dict"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(lines) + "\n", encoding="ascii")
print(f"{len(lines) - 2} words, {len(environments)} environments")
