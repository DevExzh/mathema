/// Map the Unicode compatibility superscript/subscript characters accepted by
/// KaTeX into the base scalar represented in a TeX script argument. The first
/// tuple field is `true` for a subscript and `false` for a superscript.
pub(crate) fn decode_script_scalar(ch: char) -> Option<(bool, char)> {
    Some(match ch {
        '⁰' => (false, '0'),
        '¹' => (false, '1'),
        '²' => (false, '2'),
        '³' => (false, '3'),
        '⁴' => (false, '4'),
        '⁵' => (false, '5'),
        '⁶' => (false, '6'),
        '⁷' => (false, '7'),
        '⁸' => (false, '8'),
        '⁹' => (false, '9'),
        '⁺' => (false, '+'),
        '⁻' => (false, '-'),
        '⁼' => (false, '='),
        '⁽' => (false, '('),
        '⁾' => (false, ')'),
        'ⁱ' => (false, 'i'),
        'ⁿ' => (false, 'n'),
        'ᴬ' => (false, 'A'),
        'ᴮ' => (false, 'B'),
        'ᴰ' => (false, 'D'),
        'ᴱ' => (false, 'E'),
        'ᴳ' => (false, 'G'),
        'ᴴ' => (false, 'H'),
        'ᴵ' => (false, 'I'),
        'ᴶ' => (false, 'J'),
        'ᴷ' => (false, 'K'),
        'ᴸ' => (false, 'L'),
        'ᴹ' => (false, 'M'),
        'ᴺ' => (false, 'N'),
        'ᴼ' => (false, 'O'),
        'ᴾ' => (false, 'P'),
        'ᴿ' => (false, 'R'),
        'ᵀ' => (false, 'T'),
        'ᵁ' => (false, 'U'),
        'ⱽ' => (false, 'V'),
        'ᵂ' => (false, 'W'),
        'ᵃ' => (false, 'a'),
        'ᵇ' => (false, 'b'),
        'ᶜ' => (false, 'c'),
        'ᵈ' => (false, 'd'),
        'ᵉ' => (false, 'e'),
        'ᶠ' => (false, 'f'),
        'ᵍ' => (false, 'g'),
        'ʰ' => (false, 'h'),
        'ᶦ' => (false, 'i'),
        'ʲ' => (false, 'j'),
        'ᵏ' => (false, 'k'),
        'ˡ' => (false, 'l'),
        'ᵐ' => (false, 'm'),
        'ᵒ' => (false, 'o'),
        'ᵖ' => (false, 'p'),
        'ʳ' => (false, 'r'),
        'ˢ' => (false, 's'),
        'ᵗ' => (false, 't'),
        'ᵘ' => (false, 'u'),
        'ᵛ' => (false, 'v'),
        'ʷ' => (false, 'w'),
        'ˣ' => (false, 'x'),
        'ʸ' => (false, 'y'),
        'ᶻ' => (false, 'z'),
        'ᵝ' => (false, 'β'),
        'ᵞ' => (false, 'γ'),
        'ᵟ' => (false, 'δ'),
        'ᵠ' => (false, 'ϕ'),
        'ᵡ' => (false, 'χ'),
        'ᶿ' => (false, 'θ'),
        '₀' => (true, '0'),
        '₁' => (true, '1'),
        '₂' => (true, '2'),
        '₃' => (true, '3'),
        '₄' => (true, '4'),
        '₅' => (true, '5'),
        '₆' => (true, '6'),
        '₇' => (true, '7'),
        '₈' => (true, '8'),
        '₉' => (true, '9'),
        '₊' => (true, '+'),
        '₋' => (true, '-'),
        '₌' => (true, '='),
        '₍' => (true, '('),
        '₎' => (true, ')'),
        'ₐ' => (true, 'a'),
        'ₑ' => (true, 'e'),
        'ₕ' => (true, 'h'),
        'ᵢ' => (true, 'i'),
        'ⱼ' => (true, 'j'),
        'ₖ' => (true, 'k'),
        'ₗ' => (true, 'l'),
        'ₘ' => (true, 'm'),
        'ₙ' => (true, 'n'),
        'ₒ' => (true, 'o'),
        'ₚ' => (true, 'p'),
        'ᵣ' => (true, 'r'),
        'ₛ' => (true, 's'),
        'ₜ' => (true, 't'),
        'ᵤ' => (true, 'u'),
        'ᵥ' => (true, 'v'),
        'ₓ' => (true, 'x'),
        'ᵦ' => (true, 'β'),
        'ᵧ' => (true, 'γ'),
        'ᵨ' => (true, 'ρ'),
        'ᵩ' => (true, 'ϕ'),
        'ᵪ' => (true, 'χ'),
        _ => return None,
    })
}
