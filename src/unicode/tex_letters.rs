#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn letters_and_marks_are_letters_and_the_rest_is_not() {
        for pair in LETTERS.windows(2) {
            assert!(pair[0].0 <= pair[0].1 && pair[0].1 < pair[1].0);
        }
        // A letter or mark of each kind, the first and last ones.
        for ch in "ªµºéΧжאم中あアー한𝐀𝛼𝔄ℂℜℵℎℨ\u{300}\u{338}\u{20D7}\u{3099}\u{E01EF}".chars()
        {
            assert!(is_tex_letter(ch), "{ch:?}");
        }
        // Numbers, letters of no general category L, symbols, spaces, private.
        for ch in "\u{80}\u{A0}²½′ⅰ〇Ⓐ①١∂∇∑→−…ⅆ。，（）𝟎\u{200D}\u{E000}\u{10FFFF}".chars()
        {
            assert_eq!(is_tex_letter(ch), ch == 'ⅆ', "{ch:?}");
        }
    }
}
